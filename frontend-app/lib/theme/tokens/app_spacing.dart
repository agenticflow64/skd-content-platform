/// Spacing scale from §3.1 of design-system.md.
/// Base unit is 4px. All values are multiples of the base.
class AppSpacing {
  AppSpacing._();

  /// 4px — Gap between icon and text
  static const double xs2 = 4;

  /// 8px — Chip internal padding, gap between meta elements
  static const double xs = 8;

  /// 12px — List item gap
  static const double sm = 12;

  /// 16px — Card internal padding
  static const double md = 16;

  /// 20px — Screen horizontal padding
  static const double lg = 20;

  /// 24px — Section gap
  static const double xl = 24;

  /// 32px — Large section gap (e.g. Settings sections)
  static const double xl2 = 32;

  /// 40px — Hero content spacing
  static const double xl3 = 40;

  /// 56px — Onboarding vertical padding
  static const double xl4 = 56;
}
